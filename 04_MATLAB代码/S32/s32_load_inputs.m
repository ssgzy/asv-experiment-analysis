function [saved,world,provenance] = s32_load_inputs(base,files,spec,proposal)
% Reuse both unadvanced S30 checkpoints. Change only target phase and run identity.
stages = fileparts(base);
commonPath = fullfile(stages,'S21','run_001','common_initialization.mat');
sourceWorldPath = fullfile(stages,'S28','scene','crossing_worlds.json');
worldPath = fullfile(base,'sources','earlier_crossing_world.json');
commonPin = pin(files,commonPath,spec.common_source_path,spec.common_source_sha256);
worldPin = pin(files,worldPath,spec.world_path,spec.world_sha256);
sourceWorldPin = approvedPin(files,proposal,sourceWorldPath,spec.source_world);
worldText = fileread(worldPath);
world = jsondecode(worldText);
oldWorld = jsondecode(fileread(sourceWorldPath));
assert(strcmp(world.schema,'S32_DESCRIPTIVE_ONE_PHASE_WORLD_1') && ...
    strcmp(world.status,'APPROVED_EXPLORATORY_SETTING') && strcmp(world.approval_message,spec.approval_message) && ...
    world.exposure.end_t_s_exclusive==28 && strcmp(oldWorld.schema,'S28_DESCRIPTIVE_SCENE_ONLY_1'), ...
    's32:SceneSchema');
assertTypedEqual(world.source_world,spec.source_world,'world_source_pin');
assertTypedEqual(world.only_scientific_change,proposal.only_science_input_change,'registered_only_scientific_change');
assertTypedEqual(oldWorld.shared_world,world.shared_world,'world_shared_settings');
newShip = world.worlds.EARLY_CROSSING.moving_ships;
oldShip = oldWorld.worlds.CROSSING.moving_ships;
assert(isstruct(newShip) && isscalar(newShip) && isstruct(oldShip) && isscalar(oldShip) && ...
    strcmp(newShip.id,'MOVING_01') && newShip.spawn_time_s==0 && newShip.radius_m==2.5 && ...
    isequal(reshape(newShip.initial_ne,1,[]),[30,28]) && isequal(reshape(oldShip.initial_ne,1,[]),[30,30]) && ...
    isequal(reshape(newShip.velocity_schedule,1,[]),[0,0,-1]) && ~isfield(newShip,'despawn_time_s'), ...
    's32:ApprovedTarget');
reversedShip = newShip;
reversedShip.initial_ne = oldShip.initial_ne;
assertTypedEqual(oldShip,reversedShip,'registered_world_target_E_only');
w = world.shared_world;
bounds = reshape(w.bounds_ne,1,[]);
start = reshape(w.start_ne,1,[]);
goal = reshape(w.goal_ne,1,[]);
route = w.global_route_ne;
assert(isequal(bounds,[-20,80,-80,50]) && isequal(start,[0,0]) && isequal(goal,[60,0]) && ...
    isequal(route,[0,0;60,0]) && w.duration_s==90 && w.lookahead_m==9.6 && ...
    w.sensor_range_m==35 && w.control_dt_s==.05 && w.decision_dt_s==.5 && ...
    w.safety_margin_m==3 && w.predicted_guard_admission_m==3.25 && w.goal_radius_m==5 && ...
    w.wind_mps==0 && w.wave_amplitude_m==0 && isequal(reshape(w.current_schedule,1,[]),[0,0,0]), ...
    's32:ApprovedCommonSceneValues');

saved = load(commonPath,'common','commonCase','externalRng','postdrawRng','cfg','settings');
C0 = saved.common;
assert(strcmp(C0.schema_version,'p1b-complete-state-v1') && isa(C0.external_noise_tape,'double') && ...
    isequal(size(C0.external_noise_tape),[1804,4]) && all(isfinite(C0.external_noise_tape(:))) && ...
    isequaln(C0.rng_state,saved.postdrawRng) && ~isequaln(saved.externalRng,saved.postdrawRng), ...
    's32:ArchivedNoiseAndRNG');
oldIds = {'CROSSING_FDWA','CROSSING_FVO'};
ids = {'EARLY_CROSSING_FDWA','EARLY_CROSSING_FVO'};
policies = {'FDWA','FVO'};
local = {'L1','L2'};
assert(isequal(reshape(cellstr(string(spec.case_order)),1,[]),ids) && ...
    isequal(reshape(cellstr(string(spec.world_order)),1,[]),{'EARLY_CROSSING','EARLY_CROSSING'}) && ...
    isequal(reshape(cellstr(string(spec.policy_order)),1,[]),policies) && ...
    isequal(reshape(cellstr(string(spec.local_method_order)),1,[]),local) && ...
    numel(spec.S30_initial_sources)==2,'s32:CaseOrder');
saved.C_clones=cell(1,2);saved.clone_evidence=cell(1,2);
origins=cell(1,2);
for k=1:2
    sourcePath=fullfile(stages,'S30','run_001',oldIds{k},'initial_state.mat');
    source=spec.S30_initial_sources(k);
    assert(strcmp(source.case_id,oldIds{k}),'s32:OriginCaseOrder');
    sourcePin=approvedPin(files,proposal,sourcePath,source);
    origin=load(sourcePath,'initial','cfg','settings','cloneEvidence','externalRng','postdrawRng');
    assertTypedEqual(saved.cfg,origin.cfg,'original_cfg');
    assertTypedEqual(saved.settings,origin.settings,'original_settings');
    assertTypedEqual(saved.externalRng,origin.externalRng,'original_external_rng');
    assertTypedEqual(saved.postdrawRng,origin.postdrawRng,'original_postdraw_rng');
    O=origin.initial;
    d=O.case_definition;sc=d.scene;
    assert(strcmp(d.id,['S30_' oldIds{k}]) && strcmp(d.stage,'S30_P1L') && ...
        strcmp(d.scene_id,spec.scene_identity_unchanged) && strcmp(sc.id,d.scene_id) && ...
        strcmp(d.global_method,'FIXED_STRAIGHT') && strcmp(d.strategy,policies{k}) && ...
        origin.cloneEvidence.whole_normalized_isequaln && ...
        origin.cloneEvidence.recursive_fields_classes_shapes_and_values_equal_after_normalization, ...
        's32:ArchivedOriginIdentity');
    assert(strcmp(O.schema_version,C0.schema_version) && O.next_tick==0 && O.global_epoch==0 && ...
        O.last_policy_epoch==-1 && O.external_noise_index==1 && O.sensor_sample_count==0 && ...
        O.timing_tape_index==1 && ~O.finished && ~O.collision_pending && ~O.goal_pending && ...
        strcmp(O.termination,'running') && isequal(O.x,zeros(12,1)) && isequal(O.n,zeros(2,1)) && ...
        isempty(O.pending_jobs) && isempty(O.delivered_epochs) && isempty(O.detected_static_ids), ...
        's32:UnadvancedArchivedOrigin');
    for f={'controller','rx','supervisor','policy_state','pending_jobs','detected_static_ids','delivered_epochs', ...
            'planner_states','planner_state_epochs','last_public','last_reference','sensor_ring','sensor_objects', ...
            'physics_contract','external_noise_tape','rng_state'}
        key=f{1};assertTypedEqual(C0.(key),O.(key),['initial_common_' key]);
    end
    assert(strcmp(O.timing_mode,'replay') && isequal(O.delivery_latency_tape,repmat(.05,184,1)) && ...
        d.duration_s==90 && d.delay_s==.1 && d.seed==1103 && d.payload_kg==25 && ...
        isequal(d.current_schedule,[0,0,0]) && isequal(sc.bounds_ne,bounds) && ...
        isequal(sc.start_ne,start) && isequal(sc.goal_ne,goal) && isequal(sc.global_route_ne,route) && ...
        isequal(sc.known_rectangles_ne,zeros(0,4)) && isequal(sc.hidden_rectangles_ne,zeros(0,4)) && ...
        isempty(d.known_ids) && isempty(d.hidden_ids) && isempty(sc.known_ids) && isempty(sc.hidden_ids) && ...
        sc.lookahead_m==w.lookahead_m && sc.sensor_range_m==w.sensor_range_m && ...
        sc.control_dt_s==w.control_dt_s && sc.decision_dt_s==w.decision_dt_s && ...
        sc.footprint_radius_m==w.footprint_radius_m && sc.safety_margin_m==w.safety_margin_m && ...
        sc.target_speed_mps==w.target_speed_mps && sc.maximum_speed_mps==w.maximum_speed_mps && ...
        sc.goal_radius_m==w.goal_radius_m,'s32:TypedOriginSharedCondition');
    original=struct('id',oldShip.id,'initial_ne',reshape(oldShip.initial_ne,1,[]), ...
        'spawn_time_s',oldShip.spawn_time_s,'velocity_schedule',reshape(oldShip.velocity_schedule,1,[]), ...
        'radius_m',oldShip.radius_m);
    assertTypedEqual(original,sc.moving_ships,'archived_S30_ship');
    C=O;
    C.case_definition.id=['S32_' ids{k}];
    C.case_definition.stage=spec.stage_identity;
    C.case_definition.scene.moving_ships(1).initial_ne(2)=spec.registered_target_east_m;
    registered=original;registered.initial_ne=reshape(newShip.initial_ne,1,[]);
    assertTypedEqual(registered,C.case_definition.scene.moving_ships,'registered_S32_ship');
    assert(strcmp(C.case_definition.scene_id,d.scene_id) && strcmp(C.case_definition.scene.id,sc.id) && ...
        strcmp(C.case_definition.stage,'S32_P1L'),'s32:SceneIdentityMustNotChange');
    normC=C;
    normC.case_definition.id=d.id;
    normC.case_definition.stage=d.stage;
    normC.case_definition.scene.moving_ships(1).initial_ne(2)=sc.moving_ships(1).initial_ne(2);
    assertTypedEqual(O,normC,'reverse_normalized_to_own_S30_typed_origin');
    origins{k}=sourcePin;
    saved.C_clones{k}=C;
    saved.clone_evidence{k}=struct('case_id',ids{k},'runtime_id',C.case_definition.id, ...
        'world','EARLY_CROSSING','policy',d.strategy,'expected_local',local{k},'source_case_id',oldIds{k}, ...
        'actual_scene',C.case_definition.scene,'S30_origin_pin',sourcePin,'new_world_pin',worldPin, ...
        'source_world_pin',sourceWorldPin,'whole_normalized_isequaln',isequaln(O,normC), ...
        'recursive_fields_classes_shapes_and_values_equal_after_normalization',true, ...
        'original_target_ne_m',[30,30],'new_target_ne_m',[30,28], ...
        'scene_identity_unchanged',true,'noise_exact',true,'controlled_latency_s',.05);
end
A=saved.C_clones{1};B=saved.C_clones{2};
B.case_definition.id=A.case_definition.id;B.case_definition.strategy=A.case_definition.strategy;
assertTypedEqual(A,B,'S32_within_world_only_policy_and_case_identity');
routeMetric=struct('planned_length_m',60,'total_heading_change_rad',0, ...
    'min_static_route_clearance_sampled_m',Inf,'clearance_scope','No static rectangles. Not a physical clearance outcome.');
saved.routeInfo=struct('method','FIXED_STRAIGHT','raw_path_ne',route,'global_route_ne',route, ...
    'metrics_R0',routeMetric,'metrics_R1',routeMetric,'scope','Prescribed S30 line; no route or route_metrics call.');
provenance=struct('schema','s32-two-exact-S30-typed-clones-v1','common',commonPin, ...
    'source_world',sourceWorldPin,'registered_world',worldPin,'world_json_text',worldText, ...
    'S30_initial_origins',{origins},'case_order',{ids},'local_order',{local}, ...
    'allowed_run_identity_changes',{{'case_definition.id','case_definition.stage'}}, ...
    'sole_scientific_change',proposal.only_science_input_change.field,'new_phase_passage_s',28, ...
    'case_pair_policy_only_exact',true,'clone_evidence',{saved.clone_evidence}, ...
    'no_new_initialization',true,'new_draws',0,'new_global_calls',0,'new_route_metrics_calls',0);
end

function row=pin(files,path,declaredPath,sha)
i=find(strcmp({files.path},path));
assert(strcmp(path,declaredPath) && numel(i)==1 && strcmp(files(i).sha256,sha), ...
    's32:UnboundInput','%s',path);
row=files(i);
end

function row=approvedPin(files,proposal,path,declared)
row=pin(files,path,declared.path,declared.sha256);
j=find(strcmp({proposal.source_pins.path},path));
assert(numel(j)==1 && strcmp(proposal.source_pins(j).sha256,row.sha256) && row.bytes==declared.bytes, ...
    's32:UnapprovedSource','%s',path);
end

function assertTypedEqual(a,b,path)
assert(strcmp(class(a),class(b)) && isequal(size(a),size(b)),'s32:TypedClassOrShape','%s',path);
if isstruct(a)
    fields=fieldnames(a);
    assert(isequal(fields,fieldnames(b)),'s32:TypedFields','%s',path);
    for i=1:numel(a)
        for j=1:numel(fields)
            f=fields{j};
            assertTypedEqual(a(i).(f),b(i).(f),sprintf('%s(%d).%s',path,i,f));
        end
    end
elseif iscell(a)
    for i=1:numel(a)
        assertTypedEqual(a{i},b{i},sprintf('%s{%d}',path,i));
    end
end
assert(isequaln(a,b),'s32:TypedValue','%s',path);
end
