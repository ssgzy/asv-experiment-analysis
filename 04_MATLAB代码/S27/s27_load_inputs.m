function [source,globalData,provenance] = s27_load_inputs(base,files,spec,proposal)
% Bind each approved S24 typed initial to its S21 common and S27 clone.
stageRoot = fileparts(base);
s21 = fullfile(stageRoot,'S21');
commonPath = fullfile(s21,'run_001','common_initialization.mat');
globalPath = fullfile(s21,'data','global','global_phase_result.json');
commonEntry = pinned(commonPath,files,'b1897abd0a32064000d84850381593143b9e623339f07a596a49a843465716f3');
globalEntry = pinned(globalPath,files,'5be5c22c97ca54411af63f65f8394986973264baa4fff5e39aeb03f33e8b010a');
source = load(commonPath,'common','commonCase','externalRng','postdrawRng','cfg','settings');
C = source.common;
d = C.case_definition;
assert(strcmp(C.schema_version,'p1b-complete-state-v1') && C.next_tick == 0 && C.global_epoch == 0 && ...
    C.last_policy_epoch == -1 && C.external_noise_index == 1 && C.sensor_sample_count == 0 && ...
    C.timing_tape_index == 1 && ~C.finished && ~C.collision_pending && ~C.goal_pending && ...
    strcmp(C.termination,'running'),'s27:StoredCommonUnadvanced');
assert(isequal(C.x,zeros(12,1)) && isequal(C.n,zeros(2,1)) && ...
    emptyDouble(C.controller) && emptyDouble(C.rx) && emptyDouble(C.supervisor) && emptyDouble(C.policy_state) && ...
    iscell(C.pending_jobs) && isequal(size(C.pending_jobs),[0,0]) && ...
    isa(C.delivered_epochs,'double') && isequal(size(C.delivered_epochs),[1,0]) && ...
    emptyScalarStruct(C.planner_states) && emptyScalarStruct(C.planner_state_epochs) && ...
    emptyScalarStruct(C.last_public) && emptyScalarStruct(C.last_reference), ...
    's27:StoredCommonInitialSlots');
assert(isequal(size(C.sensor_ring),[3,9]) && all(isnan(C.sensor_ring(:))) && ...
    iscell(C.sensor_objects) && isequal(size(C.sensor_objects),[3,1]) && ...
    all(cellfun(@isempty,C.sensor_objects)) && iscell(C.detected_static_ids) && ...
    isequal(size(C.detected_static_ids),[0,0]),'s27:StoredCommonSensors');
assert(isa(C.external_noise_tape,'double') && isequal(size(C.external_noise_tape),[1804,4]) && ...
    all(isfinite(C.external_noise_tape(:))) && isequaln(C.rng_state,source.postdrawRng) && ...
    isstruct(source.externalRng) && isscalar(source.externalRng) && ...
    ~isequaln(source.externalRng,source.postdrawRng),'s27:StoredCommonNoiseAndRng');
assert(strcmp(C.timing_mode,'record') && isequal(size(C.delivery_latency_tape),[184,1]) && ...
    isa(C.delivery_latency_tape,'double') && all(isnan(C.delivery_latency_tape(:))), ...
    's27:StoredCommonOriginalLatencySlots');
assert(d.duration_s == 90 && d.delay_s == .1 && d.noise_scale == 1 && d.seed == 1103 && ...
    d.injected_latency_s == .05 && d.payload_kg == 25 && isequal(d.initial_ne,[0,0]) && ...
    d.initial_heading_deg == 0 && d.initial_ur_mps == 0 && ...
    strcmp(d.strategy,'FDWA') && ~d.equal_shadow && d.recovery_enabled && ...
    isequal(d.current_schedule,[0,0,0]) && strcmp(d.expected_termination,'arrived'), ...
    's27:StoredCommonPolicyScene');
sc = d.scene;
assert(sc.control_dt_s == .05 && sc.decision_dt_s == .5 && sc.goal_radius_m == 5 && ...
    isequal(sc.bounds_ne,[-20,60,-20,60]) && isequal(sc.start_ne,[0,0]) && ...
    isequal(sc.goal_ne,[40,40]) && isequal(sc.known_rectangles_ne,[18,26,14,22]) && ...
    isempty(sc.hidden_rectangles_ne) && isempty(sc.moving_ships) && sc.safety_margin_m == 3 && ...
    abs(sc.footprint_radius_m-hypot(1,.54)) <= 1e-14 && sc.sensor_range_m == 35 && ...
    sc.lookahead_m == 30 && sc.target_speed_mps == 1.2 && sc.maximum_speed_mps == 1.2, ...
    's27:StoredCommonSceneValues');
assert(C.physics_contract.mp == 25 && C.physics_contract.V_c == 0 && C.physics_contract.beta_c == 0 && ...
    isequal(C.physics_contract.rp,[.05;0;-.35]) && ...
    C.physics_contract.n_min == source.cfg.n_min_radps && C.physics_contract.n_max == source.cfg.n_max_radps, ...
    's27:StoredCommonPhysics');
text = fileread(globalPath);
globalData = jsondecode(text);
assert(strcmp(globalData.status,'READY_FOR_MATLAB') && globalData.matlab_stage_allowed && ...
    numel(globalData.methods) == 2,'s27:FrozenGlobalPhase');
labels = {'ASTAR','THETA_STAR'};
rawCounts = [29,3];
adaptedCounts = [15,3];
for k = 1:2
    m = globalData.methods(k);
    assert(strcmp(m.method,labels{k}) && strcmp(m.status,'VALID_ROUTE') && m.matlab_case_eligible && ...
        isequal(size(m.raw_path_ne),[rawCounts(k),2]) && ...
        isequal(size(m.global_route_ne),[adaptedCounts(k),2]),'s27:FrozenGlobalIdentity');
    checkRoute(m.raw_path_ne);
    checkRoute(m.global_route_ne);
end
assert(isequaln(sc.global_route_ne,globalData.methods(1).global_route_ne),'s27:StoredCommonReferenceRoute');
assert(source.settings.control_dt_s == .05 && source.settings.compute_budget_s == .5 && ...
    source.settings.reference_ttl_s == 1 && source.settings.recovery.minimum_brake_s == 1, ...
    's27:StoredCommonSettings');
source.S24_initials = cell(1,2);
source.S27_clones = cell(1,2);
source.clone_evidence = cell(1,2);
source.initial_sources = cell(1,2);
assert(numel(spec.s24_initial_sources) == 2 && numel(proposal.input_binding.S24_two_actual_initial_states) == 2, ...
    's27:InitialSourceCount');
for k = 1:2
    caseId = labels{k};
    entry = spec.s24_initial_sources(k);
    approved = proposal.input_binding.S24_two_actual_initial_states(k);
    path = fullfile(stageRoot,'S24','run_001',caseId,'initial_state.mat');
    assert(strcmp(entry.case_id,caseId) && strcmp(entry.path,path) && strcmp(approved.path,path) && ...
        strcmp(entry.sha256,approved.sha256),'s27:InitialSourceIdentity','%s',caseId);
    binding = pinned(path,files,approved.sha256);
    assert(binding.bytes == entry.bytes,'s27:InitialSourceSize');
    origin = load(path,'initial','cfg','settings','externalRng','postdrawRng');
    assertTypedEqual(source.cfg,origin.cfg,'cfg');
    assertTypedEqual(source.settings,origin.settings,'settings');
    assertTypedEqual(source.externalRng,origin.externalRng,'externalRng');
    assertTypedEqual(source.postdrawRng,origin.postdrawRng,'postdrawRng');
    old = origin.initial;
    assert(strcmp(old.case_definition.id,['S24_' caseId]) && ...
        strcmp(old.case_definition.global_method,caseId) && ...
        isa(old.case_definition.scene.lookahead_m,'double') && isscalar(old.case_definition.scene.lookahead_m) && ...
        old.case_definition.scene.lookahead_m == 30 && strcmp(old.timing_mode,'replay') && ...
        isequal(size(old.delivery_latency_tape),[184,1]) && all(old.delivery_latency_tape == .05) && ...
        isequaln(old.case_definition.scene.global_route_ne,globalData.methods(k).global_route_ne), ...
        's27:OriginalCaseIdentity','%s',caseId);
    commonNormalized = old;
    commonNormalized.case_definition.id = C.case_definition.id;
    commonNormalized.case_definition.global_method = C.case_definition.global_method;
    commonNormalized.case_definition.scene.global_route_ne = C.case_definition.scene.global_route_ne;
    commonNormalized.timing_mode = C.timing_mode;
    commonNormalized.delivery_latency_tape = C.delivery_latency_tape;
    assertTypedEqual(C,commonNormalized,'S24_against_S21_common');
    clone = old;
    clone.case_definition.id = ['S27_' caseId];
    clone.case_definition.scene.lookahead_m = spec.registered_lookahead_m;
    normalized = clone;
    normalized.case_definition.id = old.case_definition.id;
    normalized.case_definition.scene.lookahead_m = old.case_definition.scene.lookahead_m;
    assertTypedEqual(old,normalized,'normalized_S27_initial');
    assert(clone.case_definition.scene.lookahead_m == 9.6,'s27:RegisteredLookahead');
    source.S24_initials{k} = old;
    source.S27_clones{k} = clone;
    source.initial_sources{k} = binding;
    source.clone_evidence{k} = struct('case_id',caseId,'source',binding,'source_matlab_variable','initial', ...
        'allowed_differences',{{'case_definition.id','case_definition.scene.lookahead_m'}}, ...
        'old_id',old.case_definition.id,'new_id',clone.case_definition.id, ...
        'original_lookahead_m',old.case_definition.scene.lookahead_m, ...
        'actual_lookahead_m',clone.case_definition.scene.lookahead_m, ...
        'lookahead_class',class(clone.case_definition.scene.lookahead_m), ...
        'lookahead_shape',size(clone.case_definition.scene.lookahead_m), ...
        'recursive_fields_classes_shapes_and_values_equal_after_normalization',true, ...
        'whole_normalized_isequaln',isequaln(normalized,old), ...
        'original_common_normalization_exact',true,'external_noise_tape_equal',isequaln(clone.external_noise_tape,C.external_noise_tape), ...
        'postdraw_rng_equal',isequaln(clone.rng_state,C.rng_state), ...
        'timing_contract_label','controlled_constant_0.05','engine_timing_mode',clone.timing_mode, ...
        'controlled_latency_s',.05,'latency_tape_shape',size(clone.delivery_latency_tape), ...
        'engine_strategy','FDWA','global_method',caseId);
end
provenance = struct('schema','s27-s24-typed-clone-reuse-v1','common',commonEntry,'global',globalEntry, ...
    'common_variables',{{'common','commonCase','externalRng','postdrawRng','cfg','settings'}}, ...
    'global_text',text,'original_timing_mode',C.timing_mode,'original_tape_shape',size(C.delivery_latency_tape), ...
    'noise_tape_shape',size(C.external_noise_tape),'noise_seed_provenance',1103, ...
    'new_common_init_calls',0,'new_noise_draws',0,'global_search_calls',0,'route_metrics_calls',0, ...
    'read_only_original_typed_values',true,'S24_initial_sources',{source.initial_sources}, ...
    'clone_evidence',{source.clone_evidence});
end

function checkRoute(route)
assert(isa(route,'double') && isreal(route) && all(isfinite(route(:))) && ...
    isequal(route(1,:),[0,0]) && isequal(route(end,:),[40,40]) && ...
    all(vecnorm(diff(route),2,2) > 0),'s27:FrozenRouteGeometry');
end

function row = pinned(path,files,expected)
index = find(strcmp({files.path},path));
assert(numel(index) == 1 && strcmp(files(index).sha256,expected),'s27:UnfrozenInput','%s',path);
row = files(index);
end

function yes = emptyDouble(v)
yes = isa(v,'double') && isequal(size(v),[0,0]);
end

function yes = emptyScalarStruct(v)
yes = isstruct(v) && isscalar(v) && isempty(fieldnames(v));
end

function assertTypedEqual(expected,actual,path)
assert(strcmp(class(expected),class(actual)) && isequal(size(expected),size(actual)), ...
    's27:TypedClassOrShape','%s',path);
if isstruct(expected)
    fields = fieldnames(expected);
    assert(isequal(fields,fieldnames(actual)),'s27:TypedFields','%s',path);
    for k = 1:numel(expected)
        for j = 1:numel(fields)
            name = fields{j};
            assertTypedEqual(expected(k).(name),actual(k).(name),sprintf('%s(%d).%s',path,k,name));
        end
    end
elseif iscell(expected)
    for k = 1:numel(expected)
        assertTypedEqual(expected{k},actual{k},sprintf('%s{%d}',path,k));
    end
end
assert(isequaln(expected,actual),'s27:TypedValue','%s',path);
end
