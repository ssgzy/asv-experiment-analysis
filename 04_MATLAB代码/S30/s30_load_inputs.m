function [saved,world,provenance] = s30_load_inputs(base,files,spec,proposal)
% S30 scene/strategy overlays from original, unadvanced typed S21 C only.
stages = fileparts(base);
commonPath = fullfile(stages,'S21','run_001','common_initialization.mat');
worldPath = fullfile(stages,'S28','scene','crossing_worlds.json');
commonPin = pin(commonPath,files,spec.common_source_path,spec.common_source_sha256,proposal.inputs.original_common);
worldPin = pin(worldPath,files,spec.world_path,spec.world_sha256,proposal.inputs.world);
saved = load(commonPath,'common','commonCase','externalRng','postdrawRng','cfg','settings');
worldText = fileread(worldPath);
world = jsondecode(worldText);
assert(strcmp(world.schema,'S28_DESCRIPTIVE_SCENE_ONLY_1'),'s30:SceneSchema');
assert(strcmp(world.approval_message,'05963e3c-7746-516c-b805-226ec539e9a0'),'s30:SceneApprovalIdentity');
w = world.shared_world;
bounds = reshape(w.bounds_ne,1,[]);
start = reshape(w.start_ne,1,[]);
goal = reshape(w.goal_ne,1,[]);
route = w.global_route_ne;
assert(isequal(bounds,[-20,80,-80,50]) && isequal(start,[0,0]) && ...
    isequal(goal,[60,0]) && isequal(route,[0,0;60,0]) && ...
    isempty(w.known_rectangles_ne) && isempty(w.hidden_rectangles_ne) && ...
    isempty(w.known_ids) && isempty(w.hidden_ids) && isempty(world.worlds.EMPTY.moving_ships), ...
    's30:ApprovedMap');
assert(w.duration_s==90 && w.initial_heading_deg==0 && w.initial_ur_mps==0 && ...
    w.goal_radius_m==5 && w.target_speed_mps==1.2 && w.maximum_speed_mps==1.2 && ...
    abs(w.footprint_radius_m-hypot(1,.54))<=1e-14 && w.safety_margin_m==3 && ...
    w.predicted_guard_admission_m==3.25 && w.lookahead_m==9.6 && w.sensor_range_m==35 && ...
    w.payload_kg==25 && w.control_dt_s==.05 && w.decision_dt_s==.5 && ...
    isequal(reshape(w.current_schedule,1,[]),[0,0,0]) && ...
    w.wind_mps==0 && w.wave_amplitude_m==0 && w.planned_delivery_latency_s==.05 && ...
    w.actual_candidate_plus_selector_budget_s==.5 && w.reference_ttl_s==1, ...
    's30:ApprovedCommonSceneValues');
ship0 = world.worlds.CROSSING.moving_ships;
assert(isstruct(ship0) && isscalar(ship0) && strcmp(ship0.id,'MOVING_01') && ...
    ship0.spawn_time_s==0 && isequal(reshape(ship0.initial_ne,1,[]),[30,30]) && ...
    ship0.radius_m==2.5 && isequal(reshape(ship0.velocity_schedule,1,[]),[0,0,-1]) && ...
    ~isfield(ship0,'despawn_time_s'),'s30:ApprovedTarget');
ship = struct('id',ship0.id,'initial_ne',reshape(ship0.initial_ne,1,[]), ...
    'spawn_time_s',ship0.spawn_time_s,'velocity_schedule',reshape(ship0.velocity_schedule,1,[]), ...
    'radius_m',ship0.radius_m);
noShips = repmat(ship,0,0);
assert(isequal(size(noShips),[0,0]),'s30:TypedEmptyShipArray');

C0 = saved.common;
d0 = C0.case_definition;
assert(strcmp(C0.schema_version,'p1b-complete-state-v1') && C0.next_tick==0 && ...
    C0.global_epoch==0 && C0.last_policy_epoch==-1 && C0.external_noise_index==1 && ...
    C0.sensor_sample_count==0 && C0.timing_tape_index==1 && ~C0.finished && ...
    ~C0.collision_pending && ~C0.goal_pending && strcmp(C0.termination,'running'), ...
    's30:UnadvancedTemplate');
assert(isequal(C0.x,zeros(12,1)) && isequal(C0.n,zeros(2,1)) && ...
    emptyDouble(C0.controller) && emptyDouble(C0.rx) && emptyDouble(C0.supervisor) && ...
    emptyDouble(C0.policy_state) && iscell(C0.pending_jobs) && ...
    isequal(size(C0.pending_jobs),[0,0]) && isempty(C0.detected_static_ids) && ...
    isa(C0.delivered_epochs,'double') && isequal(size(C0.delivered_epochs),[1,0]) && ...
    emptyStruct(C0.planner_states) && emptyStruct(C0.planner_state_epochs) && ...
    emptyStruct(C0.last_public) && emptyStruct(C0.last_reference),'s30:EmptyInitialExecution');
assert(isequal(size(C0.sensor_ring),[3,9]) && all(isnan(C0.sensor_ring(:))) && ...
    iscell(C0.sensor_objects) && isequal(size(C0.sensor_objects),[3,1]) && ...
    all(cellfun(@isempty,C0.sensor_objects)) && iscell(C0.detected_static_ids) && ...
    isequal(size(C0.detected_static_ids),[0,0]),'s30:EmptyInitialObservationSlots');
assert(isa(C0.external_noise_tape,'double') && isequal(size(C0.external_noise_tape),[1804,4]) && ...
    all(isfinite(C0.external_noise_tape(:))) && isequaln(C0.rng_state,saved.postdrawRng) && ...
    isstruct(saved.externalRng) && isscalar(saved.externalRng) && ...
    ~isequaln(saved.externalRng,saved.postdrawRng),'s30:OriginalNoiseAndRNG');
assert(strcmp(C0.timing_mode,'record') && isa(C0.delivery_latency_tape,'double') && ...
    isequal(size(C0.delivery_latency_tape),[184,1]) && all(isnan(C0.delivery_latency_tape(:))), ...
    's30:OriginalLatencyTemplate');
assert(d0.duration_s==90 && d0.delay_s==.1 && d0.noise_scale==1 && d0.seed==1103 && ...
    d0.injected_latency_s==.05 && d0.payload_kg==25 && isequal(d0.initial_ne,start) && ...
    d0.initial_heading_deg==0 && d0.initial_ur_mps==0 && strcmp(d0.strategy,'FDWA') && ...
    d0.recovery_enabled && ~d0.equal_shadow && isequal(d0.current_schedule,[0,0,0]) && ...
    strcmp(d0.expected_termination,'arrived'),'s30:OriginalCommonPolicyPhysics');
assert(d0.scene.control_dt_s==w.control_dt_s && d0.scene.decision_dt_s==w.decision_dt_s && ...
    d0.scene.goal_radius_m==w.goal_radius_m && d0.scene.safety_margin_m==w.safety_margin_m && ...
    d0.scene.footprint_radius_m==w.footprint_radius_m && d0.scene.sensor_range_m==w.sensor_range_m && ...
    d0.scene.target_speed_mps==w.target_speed_mps && d0.scene.maximum_speed_mps==w.maximum_speed_mps && ...
    d0.scene.lookahead_m==30 && isequal(d0.scene.known_rectangles_ne,[18,26,14,22]), ...
    's30:OriginalSceneOrigin');
assert(C0.physics_contract.mp==25 && C0.physics_contract.V_c==0 && C0.physics_contract.beta_c==0 && ...
    isequal(C0.physics_contract.rp,[.05;0;-.35]) && ...
    C0.physics_contract.n_min==saved.cfg.n_min_radps && C0.physics_contract.n_max==saved.cfg.n_max_radps && ...
    saved.cfg.control_dt_s==.05 && saved.settings.control_dt_s==.05 && ...
    saved.settings.compute_budget_s==.5 && saved.settings.reference_ttl_s==1 && ...
    saved.settings.nominal_horizon_s==4 && saved.settings.stop_horizon_s==6 && ...
    saved.settings.admission_clearance_m==3.25 && saved.settings.recovery.minimum_brake_s==1, ...
    's30:OriginalCommonSettings');

ids = {'EMPTY_FDWA','EMPTY_FVO','CROSSING_FDWA','CROSSING_FVO'};
worldNames = {'EMPTY','EMPTY','CROSSING','CROSSING'};
policies = {'FDWA','FVO','FDWA','FVO'};
local = {'L1','L2','L1','L2'};
assert(isequal(reshape(cellstr(string(spec.case_order)),1,[]),ids) && ...
    isequal(reshape(cellstr(string(spec.world_order)),1,[]),worldNames) && ...
    isequal(reshape(cellstr(string(spec.policy_order)),1,[]),policies) && ...
    isequal(reshape(cellstr(string(spec.local_method_order)),1,[]),local),'s30:CaseOrder');
dFields = {'id','global_method','stage','scene_id','strategy','known_ids','hidden_ids'};
scFields = {'id','bounds_ne','goal_ne','global_route_ne','known_rectangles_ne','known_ids', ...
    'hidden_rectangles_ne','hidden_ids','moving_ships','lookahead_m'};
saved.C_clones = cell(1,4);
saved.clone_evidence = cell(1,4);
for k = 1:4
    C = C0;
    d = d0;
    sc = d0.scene;
    d.id = ['S30_' ids{k}];
    d.global_method = spec.frozen_scene_identities.global_method;
    d.stage = spec.frozen_scene_identities.stage;
    d.scene_id = spec.frozen_scene_identities.(worldNames{k});
    d.strategy = policies{k};
    d.known_ids = cell(0,0);
    d.hidden_ids = cell(0,0);
    sc.id = d.scene_id;
    sc.bounds_ne = bounds;
    sc.goal_ne = goal;
    sc.global_route_ne = route;
    sc.known_rectangles_ne = zeros(0,4);
    sc.known_ids = cell(0,0);
    sc.hidden_rectangles_ne = zeros(0,4);
    sc.hidden_ids = cell(0,0);
    sc.moving_ships = noShips;
    if strcmp(worldNames{k},'CROSSING'),sc.moving_ships = ship;end
    sc.lookahead_m = w.lookahead_m;
    d.scene = sc;
    C.case_definition = d;
    C.timing_mode = 'replay';
    C.delivery_latency_tape = repmat(.05,184,1);
    assert(strcmp(d.strategy,policies{k}) && strcmp(d.id,['S30_' ids{k}]) && ...
        strcmp(sc.id,d.scene_id) && strcmp(d.stage,'S30_P1L') && strcmp(d.global_method,'FIXED_STRAIGHT') && ...
        isequal(sc.start_ne,start) && isequal(sc.goal_ne,goal) && isequal(sc.bounds_ne,bounds) && ...
        isequal(sc.global_route_ne,route) && isequal(sc.lookahead_m,9.6) && ...
        isequal(sc.known_rectangles_ne,zeros(0,4)) && isequal(sc.hidden_rectangles_ne,zeros(0,4)) && ...
        isempty(d.known_ids) && isempty(d.hidden_ids) && isempty(sc.known_ids) && isempty(sc.hidden_ids) && ...
        isempty(C.detected_static_ids) && C.next_tick==0 && C.external_noise_index==1 && ...
        isequaln(C.external_noise_tape,C0.external_noise_tape) && ...
        isequaln(C.rng_state,saved.postdrawRng) && strcmp(C.timing_mode,'replay') && ...
        isequal(C.delivery_latency_tape,repmat(.05,184,1)),'s30:PositiveCloneBinding');
    if strcmp(worldNames{k},'EMPTY')
        assertTypedEqual(noShips,sc.moving_ships,'empty_world_moving_list');
    else
        assertTypedEqual(ship,sc.moving_ships,'crossing_world_moving_list');
    end
    normC = C;
    for i=1:numel(dFields),key=dFields{i};normC.case_definition.(key)=d0.(key);end
    for i=1:numel(scFields),key=scFields{i};normC.case_definition.scene.(key)=d0.scene.(key);end
    normC.timing_mode = C0.timing_mode;
    normC.delivery_latency_tape = C0.delivery_latency_tape;
    assertTypedEqual(C0,normC,'reverse_normalized_original_C');
    saved.C_clones{k} = C;
    saved.clone_evidence{k} = struct('case_id',ids{k},'runtime_id',d.id,'world',worldNames{k}, ...
        'policy',d.strategy,'expected_local',local{k},'world_pin',worldPin,'common_pin',commonPin, ...
        'actual_scene',sc,'template_reverse_exact',true,'positive_scene_exact',true, ...
        'whole_normalized_isequaln',isequaln(normC,C0), ...
        'recursive_fields_classes_shapes_and_values_equal_after_normalization',true, ...
        'noise_shape',size(C.external_noise_tape),'noise_exact',true,'initial_slots_empty',true, ...
        'delivery_latency_shape',size(C.delivery_latency_tape),'controlled_latency_s',.05);
end
for pair = [1,3;2,4]
    i=pair(1);j=i+1;A=saved.C_clones{i};B=saved.C_clones{j};
    B.case_definition.id=A.case_definition.id;B.case_definition.strategy=A.case_definition.strategy;
    assertTypedEqual(A,B,'within_world_only_policy_identity');
end
for pair = [1,2;3,4]
    i=pair(1);j=pair(2);A=saved.C_clones{i};B=saved.C_clones{j};
    B.case_definition.id=A.case_definition.id;
    B.case_definition.scene_id=A.case_definition.scene_id;
    B.case_definition.scene.id=A.case_definition.scene.id;
    B.case_definition.scene.moving_ships=A.case_definition.scene.moving_ships;
    assertTypedEqual(A,B,'within_policy_only_world_identity_and_moving_list');
end
routeMetric = struct('planned_length_m',60,'total_heading_change_rad',0, ...
    'min_static_route_clearance_sampled_m',Inf, ...
    'clearance_scope','No static rectangles. This placeholder is not a physical clearance outcome.');
saved.routeInfo = struct('method','FIXED_STRAIGHT','raw_path_ne',route,'global_route_ne',route, ...
    'metrics_R0',routeMetric,'metrics_R1',routeMetric, ...
    'scope','Prescribed shared line; no global planner or route_metrics call.');
provenance = struct('schema','s30-four-typed-clones-v1','common',commonPin,'world',worldPin, ...
    'world_json_text',worldText,'case_order',{ids},'local_order',{local}, ...
    'allowed_template_case_definition_fields',{dFields},'allowed_template_scene_fields',{scFields}, ...
    'allowed_template_top_fields',{{'timing_mode','delivery_latency_tape'}}, ...
    'typed_mat_variables',{{'common','commonCase','externalRng','postdrawRng','cfg','settings'}}, ...
    'within_world_policy_only_exact',true,'within_policy_world_only_exact',true, ...
    'no_new_initialization',true,'new_draws',0,'new_global_calls',0,'new_route_metrics_calls',0, ...
    'clone_evidence',{saved.clone_evidence});
end

function row = pin(path,files,declaredPath,declaredSha,proposed)
i = find(strcmp({files.path},path));
assert(strcmp(path,declaredPath) && strcmp(path,proposed.path) && ...
    strcmp(declaredSha,proposed.sha256) && numel(i)==1 && strcmp(files(i).sha256,declaredSha), ...
    's30:UnboundInput','%s',path);
row = files(i);
end

function yes = emptyDouble(v)
yes = isa(v,'double') && isequal(size(v),[0,0]);
end

function yes = emptyStruct(v)
yes = isstruct(v) && isscalar(v) && isempty(fieldnames(v));
end

function assertTypedEqual(a,b,path)
assert(strcmp(class(a),class(b)) && isequal(size(a),size(b)),'s30:TypedClassOrShape','%s',path);
if isstruct(a)
    fields=fieldnames(a);
    assert(isequal(fields,fieldnames(b)),'s30:TypedFields','%s',path);
    for i=1:numel(a)
        for j=1:numel(fields)
            f=fields{j};
            assertTypedEqual(a(i).(f),b(i).(f),sprintf('%s(%d).%s',path,i,f));
        end
    end
elseif iscell(a)
    for i=1:numel(a)
        assertTypedEqual(a{i},b{i},sprintf('%s{%d}',path,i));
    end
end
assert(isequaln(a,b),'s30:TypedValue','%s',path);
end
