  assert(nextChunk<=upper.chunks && counts.chunks_durable<upper.chunks,'s35:ChunkBound');
  path=fullfile(currentFolder,sprintf('chunk_%03d.mat',nextChunk));
  chunk=struct('schema','s35-all-returned-rows-v1','case_id',caseId,'policy','FVO', ...
   'chunk_index',nextChunk,'first_tick',rows{1}.tick,'last_tick',rows{end}.tick,'count',numel(rows), ...
   'rows',{rows},'job_timing',{jobTimingRows},'pretarget',{preflightRows}, ...
   'timing_contract_label','controlled_constant_0.05','engine_timing_mode','replay','controlled_latency_s',.05, ...
   'actual_lookahead_m',initial.case_definition.scene.lookahead_m,'counts_before_durable_commit',counts, ...
   'C_after',C,'currentStats',currentStats,'intervals_durable_after_this_commit',counts.intervals_durable+numel(rows));
  tmp=[path '.tmp.mat'];save(tmp,'chunk','-v7');[ok,msg]=movefile(tmp,path);assert(ok,'s35:ChunkCommit','%s',msg);
  chunkIndex=nextChunk;counts.intervals_durable=counts.intervals_durable+numel(rows);
  counts.chunks_durable=counts.chunks_durable+1;
  counts.pretarget_dispatch_records_durable=counts.pretarget_dispatch_records_durable+numel(preflightRows);durableCounts=counts;
  chunkPaths{end+1}=path;rows={};jobTimingRows={};preflightRows={};writeWall=writeWall+toc(timerWrite);journal('chunk_committed');
 end
end

