function target=lookaheadTarget(route,ne,lookahead)
% Pure geometry check of the archived L2 routeLookahead; no candidate/model call.
seg=hypot(diff(route(:,1)),diff(route(:,2)));cum=[0;cumsum(seg)];best=inf;s0=0;
for k=1:size(route,1)-1
 a=route(k,:);v=route(k+1,:)-a;u=max(0,min(1,dot(ne-a,v)/dot(v,v)));q=a+u*v;
 dist=hypot(ne(1)-q(1),ne(2)-q(2));
 if dist<best,best=dist;s0=cum(k)+u*seg(k);end
end
s=min(cum(end),s0+lookahead);k=find(cum<=s,1,'last');
if k>=size(route,1),target=route(end,:);return;end
u=(s-cum(k))/seg(k);target=route(k,:)+u*(route(k+1,:)-route(k,:));
end

function [book,first]=updateHandoff(book,first,row,chunkIndex,rowIndex)
source=struct('chunk_index',chunkIndex,'row_index_1based',rowIndex,'tick',row.tick,'t_s',row.t_s);
if ~isempty(row.job_bundles)
 b=row.job_bundles{1};p=b.selected_packet;j=b.jobs{1};seq=p.sequence;
 assert(seq>=1 && seq<=numel(book) && isempty(book{seq}),'s35:HandoffDuplicateGeneration');
 book{seq}=struct('sequence',seq,'reference_id',p.reference_id,'packet',p, ...
  'generation',source,'target_ne',j.decision.target_ne, ...
  'selected_speed_mps',j.decision.target_speed_mps,'selected_heading_rad',j.decision.target_heading_rad, ...
  'received',[],'accepted',[],'activated',[],'rejection',[],'first_effective',[]);
end
for k=1:numel(row.received)
 a=row.received{k};p=a.packet;seq=p.sequence;x=book{seq};
 assert(~isempty(x) && isequaln(p,x.packet) && isempty(x.received),'s35:HandoffReceiveIdentity');
 x.received=struct('source',source,'arrival_time',a.arrival_time, ...
  'scheduled_arrival_time',a.scheduled_arrival_time,'causally_eligible',a.causally_eligible);
 book{seq}=x;
end
for k=1:numel(row.receiver_events)
 e=row.receiver_events(k);
 if ~isfinite(e.sequence),continue;end
 seq=e.sequence;x=book{seq};
 assert(~isempty(x) && strcmp(e.reference_id,x.reference_id),'s35:HandoffEventIdentity');
 switch e.event
  case 'accepted',x.accepted=struct('source',source,'event',e);
  case 'activated',x.activated=struct('source',source,'event',e);
  case 'rejected',x.rejection=struct('source',source,'event',e);
 end
 book{seq}=x;
end
a=row.action;
if ~(a.reference_fresh==1 && a.fallback==0 && a.supervisor_latched==0 && ...
 strcmp(char(a.supervisor_mode),'TRACK') && strcmp(char(a.execution_source),'PLANNER')),return;end
seq=a.reference_sequence;x=book{seq};
assert(~isempty(x),'s35:EffectiveCommandWithoutGeneration');p=x.packet;
assert(strcmp(p.status,'ok') && ...
 strcmp(char(a.active_reference_id),p.reference_id) && strcmp(char(a.active_planner_id),'L2') && ...
 ~isempty(x.received) && x.received.causally_eligible && ~isempty(x.accepted) && ~isempty(x.activated) && ...
 p.generated_from_time<=x.received.arrival_time && x.received.arrival_time<=x.accepted.event.t_s && ...
 x.accepted.event.t_s<=x.activated.event.t_s && x.activated.event.t_s<=row.t_s, ...
 's35:EffectiveCommandPacketIdentity');
if ~isempty(x.first_effective),return;end
r=row.prediction.nominal_reference;
assert(r.fresh && ~r.fallback && r.sequence==seq && strcmp(r.reference_id,p.reference_id) && ...
 r.speed_mps==a.target_speed_raw_mps && r.heading_rad==a.target_heading_rad, ...
 's35:EffectiveControlReference');
witness=struct('source',source,'sequence',seq,'reference_id',p.reference_id,'generation',x.generation, ...
 'received',x.received,'accepted',x.accepted,'activated',x.activated, ...
 'guard_preview_reference',r,'controller_estimate',row.prediction.public_input.control_estimate, ...
 'controller_state_before',row.handoff.before.controller, ...
 'controller_reference_speed_mps',a.target_speed_raw_mps,'controller_reference_heading_rad',a.target_heading_rad, ...
 'shaft_commands_radps',[a.n_cmd_left_radps,a.n_cmd_right_radps], ...
 'fresh',a.reference_fresh,'fallback',a.fallback,'mode',char(a.supervisor_mode),'execution_source',char(a.execution_source));
x.first_effective=witness;book{seq}=x;
if isempty(first),first=witness;end
end
