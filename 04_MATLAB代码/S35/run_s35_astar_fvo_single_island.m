function records=verifyFreeze(files)
records=struct('path',{},'sha256',{},'bytes',{});
for k=1:numel(files)
 info=dir(files(k).path);assert(isscalar(info) && ~info.isdir,'s35:FrozenSourceMissing','%s',files(k).path);
