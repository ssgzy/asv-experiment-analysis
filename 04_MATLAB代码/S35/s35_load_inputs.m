function [saved,provenance]=s35_load_inputs(base,files,spec,proposal)
% Before setup: bind original A* solver output, original S27 typed C and its saved RNG.
stages=fileparts(base);
originPath=fullfile(stages,'S27','run_001','ASTAR','initial_state.mat');
bindingPath=fullfile(stages,'S27','run_001','actual_global_inputs.json');
solverPath=fullfile(stages,'S21','data','global','global_phase_result.json');
originPin=approvedPin(files,proposal,originPath,spec.S27_original_initial);
bindingPin=approvedPin(files,proposal,bindingPath,spec.S27_actual_global_inputs);
solverPin=pin(files,solverPath,spec.S21_archived_global_result);
assert(strcmp(originPin.sha256,'3a2734074fc0f82c20d62ac890e6419f628e4a69a11673c57006c1565eda9044') && ...
    strcmp(solverPin.sha256,'5be5c22c97ca54411af63f65f8394986973264baa4fff5e39aeb03f33e8b010a'), ...
    's35:PriorStageInputIdentity');

saved=load(originPath,'initial','cfg','settings','externalRng','postdrawRng','cloneEvidence');
assert(isequal(sort(fieldnames(saved)),sort({'initial';'cfg';'settings';'externalRng';'postdrawRng';'cloneEvidence'})), ...
    's35:ArchiveVariables');
O=saved.initial;
d=O.case_definition;sc=d.scene;
assert(strcmp(O.schema_version,'p1b-complete-state-v1') && O.next_tick==0 && O.global_epoch==0 && ...
    O.last_policy_epoch==-1 && O.external_noise_index==1 && O.sensor_sample_count==0 && ...
    O.timing_tape_index==1 && ~O.finished && ~O.collision_pending && ~O.goal_pending && ...
    strcmp(O.termination,'running') && isequal(O.x,zeros(12,1)) && isequal(O.n,zeros(2,1)), ...
    's35:OriginNotAdvanced');
assert(isempty(O.controller) && isempty(O.rx) && isempty(O.supervisor) && isempty(O.policy_state) && ...
    isempty(O.pending_jobs) && isempty(O.delivered_epochs) && isempty(O.detected_static_ids) && ...
    emptyScalarStruct(O.planner_states) && emptyScalarStruct(O.planner_state_epochs) && ...
    emptyScalarStruct(O.last_public) && emptyScalarStruct(O.last_reference) && ...
    isequal(size(O.sensor_ring),[3,9]) && all(isnan(O.sensor_ring(:))) && ...
    iscell(O.sensor_objects) && isequal(size(O.sensor_objects),[3,1]) && all(cellfun(@isempty,O.sensor_objects)), ...
    's35:OriginHistoryAndObservationEmpty');
assert(isa(O.external_noise_tape,'double') && isequal(size(O.external_noise_tape),[1804,4]) && ...
    all(isfinite(O.external_noise_tape(:))) && isstruct(saved.externalRng) && isscalar(saved.externalRng) && ...
    isequaln(O.rng_state,saved.postdrawRng) && ~isequaln(saved.externalRng,saved.postdrawRng) && ...
    strcmp(spec.external_rng_source.path,originPath) && strcmp(spec.external_rng_source.var,'externalRng') && ...
    strcmp(spec.external_rng_source.postdraw_var,'postdrawRng') && ~spec.external_rng_source.sidecar_required, ...
    's35:OriginalNoiseAndDistinctRng');
assert(strcmp(O.timing_mode,'replay') && isequal(O.delivery_latency_tape,repmat(.05,184,1)) && ...
    strcmp(spec.contract_label,'controlled_constant_0.05') && strcmp(spec.engine_timing_mode,O.timing_mode) && ...
    spec.constant_latency_s==.05 && spec.duration_s==90 && spec.registered_lookahead_m==9.6, ...
    's35:OriginalControlledDelivery');
assert(strcmp(d.id,spec.origin_case_id) && strcmp(d.id,'S27_ASTAR') && ...
    strcmp(d.stage,spec.origin_stage) && strcmp(d.stage,'S21_P1G') && strcmp(d.global_method,'ASTAR') && ...
    strcmp(d.scene_id,spec.scene_identity_unchanged) && strcmp(d.scene_id,'P1G') && strcmp(sc.id,d.scene_id) && ...
    strcmp(d.strategy,spec.origin_strategy) && strcmp(d.strategy,'FDWA') && ...
    any(strcmp(d.candidate_methods,'L2')) && any(strcmp(d.registry_methods,'L2')) && ~d.equal_shadow && ...
    d.recovery_enabled && d.duration_s==90 && d.seed==1103 && d.delay_s==.1 && d.noise_scale==1 && ...
    d.injected_latency_s==.05 && d.payload_kg==25 && isequal(d.initial_ne,[0,0]) && ...
    d.initial_heading_deg==0 && d.initial_ur_mps==0 && isequal(d.current_schedule,[0,0,0]) && ...
    strcmp(d.expected_termination,'arrived'),'s35:OriginalCaseIdentityAndConditions');
assert(saved.cloneEvidence.whole_normalized_isequaln && ...
    saved.cloneEvidence.recursive_fields_classes_shapes_and_values_equal_after_normalization && ...
    strcmp(saved.cloneEvidence.global_method,'ASTAR') && saved.cloneEvidence.actual_lookahead_m==9.6, ...
    's35:PriorCloneProof');
assert(isequal(sc.bounds_ne,[-20,60,-20,60]) && isequal(sc.start_ne,[0,0]) && isequal(sc.goal_ne,[40,40]) && ...
    isequal(sc.known_rectangles_ne,[18,26,14,22]) && isequal(reshape(spec.known_rectangles_ne,1,[]),sc.known_rectangles_ne) && ...
    isequal(sc.known_ids,{'RECT_01'}) && isequal(sc.known_ids,d.known_ids) && ...
    isequal(reshape(cellstr(string(spec.known_ids)),1,[]),sc.known_ids) && ...
    isempty(sc.hidden_rectangles_ne) && isempty(sc.hidden_ids) && isempty(d.hidden_ids) && isempty(sc.moving_ships) && ...
    sc.lookahead_m==9.6 && sc.control_dt_s==.05 && sc.decision_dt_s==.5 && sc.goal_radius_m==5 && ...
    sc.safety_margin_m==3 && sc.sensor_range_m==35 && sc.target_speed_mps==1.2 && sc.maximum_speed_mps==1.2 && ...
    abs(sc.footprint_radius_m-hypot(1,.54))<=1e-14, ...
    's35:PositiveOriginalStaticScene');
assert(O.physics_contract.mp==25 && O.physics_contract.V_c==0 && O.physics_contract.beta_c==0 && ...
    isequal(O.physics_contract.rp,[.05;0;-.35]) && ...
    O.physics_contract.n_min==saved.cfg.n_min_radps && O.physics_contract.n_max==saved.cfg.n_max_radps && ...
    saved.cfg.control_dt_s==.05 && saved.settings.control_dt_s==.05 && saved.settings.compute_budget_s==.5 && ...
    saved.settings.reference_ttl_s==1 && saved.settings.nominal_horizon_s==4 && saved.settings.stop_horizon_s==6 && ...
    saved.settings.admission_clearance_m==3.25 && saved.settings.recovery.minimum_brake_s==1, ...
    's35:UnchangedPhysicalAndGuardSettings');

prior=jsondecode(fileread(bindingPath));
solverText=fileread(solverPath);
G=jsondecode(solverText);
assert(strcmp(prior.global_phase_path,solverPath) && strcmp(prior.global_phase_sha256,solverPin.sha256) && ...
    strcmp(prior.global_phase_json_text,solverText) && prior.actual_lookahead_m==9.6 && ...
    prior.controlled_latency_s==.05 && strcmp(prior.engine_timing_mode,'replay'), ...
    's35:ExactPriorSolverArchive');
assert(strcmp(G.status,'READY_FOR_MATLAB') && G.matlab_stage_allowed && numel(G.methods)==2 && ...
    strcmp(G.methods(1).method,'ASTAR') && strcmp(prior.global_results.methods(1).method,'ASTAR'), ...
    's35:RegisteredGlobalMethod');
M=G.methods(1);P=prior.global_results.methods(1);w=G.scene_map;
assert(strcmp(M.status,'VALID_ROUTE') && M.matlab_case_eligible && M.validity.passed && M.validity.adapter_exact && ...
    isequal(size(M.raw_path_ne),[29,2]) && isequal(size(M.global_route_ne),[15,2]) && ...
    isequal(M.raw_path_ne,P.raw_path_ne) && isequal(M.global_route_ne,P.global_route_ne) && ...
    isequal(M.global_route_ne,sc.global_route_ne) && ...
    isequal(M.raw_path_ne(1,:),sc.start_ne) && isequal(M.raw_path_ne(end,:),sc.goal_ne) && ...
    isequal(M.global_route_ne(1,:),sc.start_ne) && isequal(M.global_route_ne(end,:),sc.goal_ne) && ...
    all(isfinite(M.raw_path_ne(:))) && all(isfinite(M.global_route_ne(:))) && ...
    isequal(reshape(w.obstacles_ne,1,[]),sc.known_rectangles_ne) && ...
    isequal(reshape(w.bounds_ne,1,[]),sc.bounds_ne) && ...
    isequal(reshape(w.start_ne,1,[]),sc.start_ne) && isequal(reshape(w.goal_ne,1,[]),sc.goal_ne), ...
    's35:OriginalAstarR0R1AndIslandBinding');
% Global planning inflation is provenance only. Raw rectangle bounds stay in actual C.
assert(w.planning_inflation_m>sc.safety_margin_m && w.safety_margin_m==sc.safety_margin_m && ...
    w.footprint_radius_m==sc.footprint_radius_m,'s35:GlobalInflationScope');

C=O;
C.case_definition.strategy=spec.policy;
C.case_definition.id=spec.runtime_case_id;
C.case_definition.stage=spec.stage_identity;
assert(strcmp(spec.case_id,'ASTAR_FVO_SINGLE_ISLAND') && ...
    strcmp(C.case_definition.id,'S35_ASTAR_FVO_SINGLE_ISLAND') && strcmp(C.case_definition.stage,'S35_P1L') && ...
    strcmp(C.case_definition.strategy,'FVO') && strcmp(spec.local_method,'L2') && ...
    strcmp(C.case_definition.scene_id,'P1G') && strcmp(C.case_definition.scene.id,'P1G'), ...
    's35:ApprovedCloneIdentities');
assertTypedEqual(sc,C.case_definition.scene,'exact_original_scene_in_actual_clone');
R=C;
R.case_definition.id=d.id;
R.case_definition.stage=d.stage;
R.case_definition.strategy=d.strategy;
assertTypedEqual(O,R,'reverse_normalized_exact_to_S27_ASTAR_initial');

saved.origin=O;
saved.clone=C;
saved.routeInfo=M;
saved.clone_evidence=struct('case_id',spec.case_id,'runtime_id',C.case_definition.id,'source',originPin, ...
    'source_matlab_variable','initial','old_id',d.id,'old_stage',d.stage,'old_strategy',d.strategy, ...
    'scene_id_unchanged',d.scene_id,'new_stage',C.case_definition.stage,'new_strategy',C.case_definition.strategy, ...
    'expected_local','L2','global_method','ASTAR','route_scene_exact',true,'actual_scene',sc, ...
    'whole_normalized_isequaln',isequaln(O,R), ...
    'recursive_fields_classes_shapes_and_values_equal_after_normalization',true, ...
    'allowed_differences',{{'case_definition.id','case_definition.stage','case_definition.strategy'}}, ...
    'noise_tape_shape',size(C.external_noise_tape),'latency_tape_shape',size(C.delivery_latency_tape), ...
    'external_rng_variable','externalRng','saved_postdraw_rng_variable','postdrawRng');
provenance=struct('schema','s35-exact-astar-to-fvo-typed-origin-v1','typed_origin',originPin, ...
    'S27_actual_global_inputs',bindingPin,'S21_original_global_result',solverPin, ...
    'source_matlab_variables',{{'initial','cfg','settings','externalRng','postdrawRng','cloneEvidence'}}, ...
    'clone_evidence',saved.clone_evidence,'R0_node_count',size(M.raw_path_ne,1), ...
    'R1_node_count',size(M.global_route_ne,1),'source_R0_NE_m',M.raw_path_ne,'source_R1_NE_m',M.global_route_ne, ...
    'map_raw_rectangle_NE_m',sc.known_rectangles_ne,'map_known_ids',{sc.known_ids}, ...
    'planning_inflation_m_provenance_only',w.planning_inflation_m, ...
    'new_global_calls',0,'new_route_metrics_calls',0,'new_initialization_calls',0,'new_noise_draws',0);
end

function row=pin(files,path,declared)
i=find(strcmp({files.path},path));
assert(strcmp(path,declared.path) && numel(i)==1 && ...
    strcmp(files(i).sha256,declared.sha256) && files(i).bytes==declared.bytes, ...
    's35:UnfrozenInput','%s',path);
row=files(i);
end

function row=approvedPin(files,proposal,path,declared)
row=pin(files,path,declared);
i=find(strcmp({proposal.source_pins.path},path));
assert(numel(i)==1 && strcmp(proposal.source_pins(i).sha256,row.sha256), ...
    's35:UnapprovedInput','%s',path);
end

function yes=emptyScalarStruct(x)
yes=isstruct(x) && isscalar(x) && isempty(fieldnames(x));
end

function assertTypedEqual(a,b,path)
assert(strcmp(class(a),class(b)) && isequal(size(a),size(b)),'s35:TypedClassOrShape','%s',path);
if isstruct(a)
    fields=fieldnames(a);
    assert(isequal(fields,fieldnames(b)),'s35:TypedFields','%s',path);
    for i=1:numel(a)
        for j=1:numel(fields)
            f=fields{j};
            assertTypedEqual(a(i).(f),b(i).(f),sprintf('%s(%d).%s',path,i,f));
        end
    end
elseif iscell(a)
    for i=1:numel(a)
        assertTypedEqual(a{i},b{i},sprintf('%s{%d}',path,i));
    end
end
assert(isequaln(a,b),'s35:TypedValue','%s',path);
end
